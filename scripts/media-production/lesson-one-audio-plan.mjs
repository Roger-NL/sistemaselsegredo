#!/usr/bin/env node
/**
 * Local planning only: no provider calls, credentials, downloads or synthesis.
 * Node >=22.18 (native TypeScript stripping); no application dependencies.
 *
 * node scripts/media-production/lesson-one-audio-plan.mjs
 * node scripts/media-production/lesson-one-audio-plan.mjs --check --self-test
 * node scripts/media-production/lesson-one-audio-plan.mjs --catalog path/to/catalog.json
 */
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE = "src/features/first-encounters/lesson-one.ts";
const UI_SOURCE = "src/features/first-encounters/LessonOne.tsx";
const OUTPUT = "output/lesson-one-audio/plan.json";
const PUBLIC_PREFIX = "/first-encounters/audio/lesson-one";
const PEOPLE = ["ana", "leo", "maya", "sam", "nina"];
const READER = "nina";
const BREAK = '<break time="0.8s" />';
// Already generated by the root agent; never spend credits regenerating Ana.
const RECORDED_BUNDLES = [{ person: "ana", texts: ["I am Ana.", "We are a team.", "They are a team."], inputFormat: "ssml", inputCharactersConfirmed: 81, approximateSecondsConfirmed: 7, status: "root-confirmed-generated-do-not-regenerate", sourceFile: null }];
const chars = value => [...value].length;
const sha = value => createHash("sha256").update(value).digest("hex");
const keyFor = (person, text) => `${person}:${text}`;
const slug = text => text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const { LESSON_SCENES, PERSON_NAMES, phraseText, evaluatePhrase, evaluateSpeaker, evaluateTeam } = await import(pathToFileURL(path.join(ROOT, SOURCE)).href);
const sourceText = await readFile(path.join(ROOT, SOURCE), "utf8");
const uiText = await readFile(path.join(ROOT, UI_SOURCE), "utf8");

function readUiModels(source) {
  const match = source.match(/const\s+MODELS\s*=\s*(\[[\s\S]*?\n\]);/);
  assert(match, "MODELS must remain auditable as a literal array in LessonOne.tsx");
  const models = JSON.parse(match[1].replace(/,\s*([\]}])/g, "$1"));
  assert.equal(models.length, 6, "There must be one model pair per game");
  for (const row of models) assert(row.length === 4 && row.every(item => typeof item === "string"), "Each model pair has two English labels and two Portuguese explanations");
  return models;
}
const UI_MODELS = readUiModels(uiText);

function canonicalPhrase(value) {
  if (!value || typeof value !== "object") return false;
  if (value.verb !== (value.pronoun === "I" ? "am" : "are")) return false;
  if (["I", "you"].includes(value.pronoun)) return Object.values(PERSON_NAMES).includes(value.complement);
  return ["we", "they"].includes(value.pronoun) && value.complement === "a team";
}
function concreteTurns(scenes) {
  return scenes.flatMap(scene => scene.rounds.flatMap(round => round.ensemble
    ? round.ensemble.map((turn, index) => ({ scene, round: turn, container: round, index }))
    : [{ scene, round, container: null, index: 0 }]));
}
function correctActors(round) {
  if (round.kind === "speaker") return (round.candidateSpeakers ?? [round.speaker]).filter(person => evaluateSpeaker(round, person).correct);
  if (round.kind === "join") {
    assert(evaluateTeam(round, [...new Set([...round.team, round.speaker])]).correct, `${round.id}: joined speaker must make the fixed phrase true`);
  } else assert(evaluatePhrase(round, round.expected).correct, `${round.id}: expected actor phrase must be correct`);
  return [round.speaker];
}
function completeModelFragments(scenes) {
  const verbGame = scenes.find(scene => scene.game === 3 && scene.mode === "game");
  assert(verbGame, "The am/are game is needed as the complete model source");
  const byPrefix = new Map(verbGame.rounds.map(round => [round.expected.pronoun === "I" ? "I am" : `${round.expected.pronoun[0].toUpperCase()}${round.expected.pronoun.slice(1)} are`, phraseText(round.expected)]));
  assert.equal(byPrefix.size, 4, "The complete examples must cover all four forms");
  return byPrefix;
}
function expandModels(scenes, models) {
  const complete = completeModelFragments(scenes);
  const knownFull = new Set(complete.values());
  return models.flatMap((row, game) => [0, 2].map((column, card) => {
    const spokenEnglish = row[column].split("·").map(part => part.trim()).map(part => {
      if (knownFull.has(part)) return part;
      const expanded = complete.get(part);
      assert(expanded, `Unmapped English model fragment: ${part}. Do not synthesize Portuguese explanations or incomplete text.`);
      return expanded;
    });
    return { game: game + 1, card: card + 1, visibleEnglish: row[column], spokenEnglish, keys: spokenEnglish.map(text => keyFor(READER, text)) };
  }));
}

export function buildAudioPlan({ scenes = LESSON_SCENES, models = UI_MODELS, catalog = {}, catalogSources = [] } = {}) {
  const assets = new Map();
  const uses = [];
  const coverage = [];
  function recordUse({ id, person, text, scope, phase, sceneId, roundId, actor = null, quoted = false, anonymous = false, candidate = null }) {
    const key = keyFor(person, text);
    if (!assets.has(key)) {
      const hash = sha(key).slice(0, 12);
      const filename = `${person}-${slug(text)}-${hash}.mp3`;
      const publicUrl = `${PUBLIC_PREFIX}/${filename}`;
      const cached = typeof catalog[key] === "string" ? catalog[key] : catalog[key]?.audioUrl ?? catalog[key]?.publicUrl ?? null;
      assets.set(key, { key, person, text, characters: chars(text), contentHash: sha(key), filename, filePath: `public${publicUrl}`, publicUrl, roles: [], useIds: [], existingCatalogUrl: cached, productionAction: cached ? "reuse-published-asset" : RECORDED_BUNDLES.some(bundle => bundle.person === person && bundle.texts.includes(text)) ? "reuse-confirmed-generated-bundle" : "reuse-if-already-generated-else-produce-once" });
    }
    const asset = assets.get(key);
    const role = quoted ? "neutral-reader" : "actor";
    if (!asset.roles.includes(role)) asset.roles.push(role);
    asset.useIds.push(id);
    uses.push({ id, key, person, text, scope, phase, sceneId, roundId, actor, quoted, anonymous, ...(candidate ? { candidate } : {}) });
    return key;
  }

  const turns = concreteTurns(scenes);
  for (const { scene, round, container } of turns) {
    assert(canonicalPhrase(round.expected), `${round.id}: never synthesize malformed grammar`);
    const actors = correctActors(round);
    assert(actors.length, `${round.id}: no correct actor available`);
    const actorKeys = actors.map(person => recordUse({
      id: `${scene.id}/${round.id}/accepted/${person}`, person, text: phraseText(round.expected),
      scope: "correct-actor-model", phase: container?.kind === "messages" ? "after-anonymous-solution-revealed" : "after-answer-accepted",
      sceneId: scene.id, roundId: round.id, actor: person, anonymous: Boolean(container?.anonymous || round.anonymous),
    }));
    coverage.push({ sceneId: scene.id, roundId: round.id, containerId: container?.id ?? null, actorKeys, canonicalWalkthroughKey: keyFor(round.speaker, phraseText(round.expected)) });
    if (container?.kind === "messages") recordUse({ id: `${scene.id}/${round.id}/anonymous-reader`, person: READER, text: phraseText(round.expected), scope: "anonymous-message-reading", phase: "before-anonymous-solution", sceneId: scene.id, roundId: round.id, quoted: true, anonymous: true });
  }

  for (const scene of scenes) for (const round of scene.rounds) {
    if (["join", "speaker"].includes(round.kind)) recordUse({ id: `${scene.id}/${round.id}/fixed-preview`, person: READER, text: phraseText(round.expected), scope: "fixed-phrase-preview", phase: "before-answer", sceneId: scene.id, roundId: round.id, quoted: true });
    if (["bubbles", "ensemble"].includes(round.kind)) for (const [index, candidate] of (round.bubbleChoices ?? []).entries()) {
      assert(canonicalPhrase(candidate), `${round.id}: option previews may contain only grammatical complete phrases`);
      recordUse({ id: `${scene.id}/${round.id}/option/${index}`, person: READER, text: phraseText(candidate), scope: "visible-option-preview", phase: "before-answer", sceneId: scene.id, roundId: round.id, quoted: true, candidate: { grammatical: true, assertedInScene: false } });
    }
    if (["verb", "build"].includes(round.kind)) {
      const candidates = round.kind === "verb" ? [round.expected] : (round.referent === "team" ? ["we", "they"] : ["I", "you"]).map(pronoun => ({ pronoun, verb: pronoun === "I" ? "am" : "are", complement: round.expected.complement }));
      for (const [index, candidate] of candidates.entries()) {
        assert(canonicalPhrase(candidate));
        recordUse({ id: `${scene.id}/${round.id}/assembled/${index}`, person: READER, text: phraseText(candidate), scope: "complete-assembled-preview", phase: "after-complete-grammatical-assembly", sceneId: scene.id, roundId: round.id, quoted: true, candidate: { grammatical: true, assertedInScene: false } });
      }
    }
  }
  const modelCards = expandModels(scenes, models);
  for (const card of modelCards) for (const [index, text] of card.spokenEnglish.entries()) recordUse({ id: `model/${card.game}/${card.card}/${index}`, person: READER, text, scope: "model-dialog-english", phase: "explicit-model-request-with-support", sceneId: `lesson-${String(card.game * 2 - 1).padStart(2, "0")}`, roundId: null, quoted: true });

  const rank = text => text.startsWith("I am ") ? 0 : text.startsWith("You are ") ? 1 : text.startsWith("We are ") ? 2 : 3;
  const list = [...assets.values()].sort((a, b) => PEOPLE.indexOf(a.person) - PEOPLE.indexOf(b.person) || rank(a.text) - rank(b.text) || a.text.localeCompare(b.text, "en"));
  for (const asset of list) { asset.roles.sort(); asset.useIds.sort(); }
  const voices = PEOPLE.map(person => ({ person, displayName: PERSON_NAMES[person], selection: "distinct-stock-elevenlabs-voice", voiceId: null, voiceName: null, cloning: false, bindingStatus: "assign-existing-stock-voice-before-production" }));
  const bundles = PEOPLE.map(person => {
    const items = list.filter(asset => asset.person === person);
    const plainText = items.map(asset => asset.text).join("\n\n");
    let offset = 0;
    const segments = items.map((asset, index) => {
      const segment = { key: asset.key, text: asset.text, startChar: offset, endCharExclusive: offset + asset.characters, filePath: asset.filePath, publicUrl: asset.publicUrl };
      offset += asset.characters + (index < items.length - 1 ? 2 : 0);
      return segment;
    });
    const pending = items.filter(asset => !asset.existingCatalogUrl && asset.productionAction !== "reuse-confirmed-generated-bundle");
    const ssmlCandidate = items.map(asset => asset.text).join(BREAK);
    return {
      person, voiceSlot: person, texts: items.map(asset => asset.text), generationStatus: RECORDED_BUNDLES.some(bundle => bundle.person === person) ? "already-generated-do-not-regenerate" : "pending", assetKeys: items.map(asset => asset.key), pendingAssetKeys: pending.map(asset => asset.key),
      requestCountIfBundled: pending.length ? 1 : 0,
      plainText, separator: "\n\n", textCharacters: chars(plainText), uniquePhraseCharacters: items.reduce((sum, asset) => sum + asset.characters, 0),
      pendingPlainText: pending.map(asset => asset.text).join("\n\n"), pendingTextCharacters: chars(pending.map(asset => asset.text).join("\n\n")),
      segments,
      breakSeparatedCandidate: { status: "proposal-only-provider-model-support-not-verified", separator: BREAK, text: ssmlCandidate, charactersIncludingMarkup: chars(ssmlCandidate), requirement: "Verify ElevenLabs model support before submitting break tags. Do not assume tags are free or supported; plain text remains available." },
      outputBundlePath: `output/lesson-one-audio/${person}-bundle-${sha(plainText).slice(0, 12)}.mp3`,
      segmentation: "One final file per asset key is required. Reuse existing files; align and verify phrase boundaries before publishing. No audio is generated by this planner.",
    };
  });
  const actorUses = uses.filter(item => !item.quoted);
  const previewUses = uses.filter(item => item.quoted);
  const actorKeys = new Set(actorUses.map(item => item.key));
  const readerKeys = new Set(previewUses.map(item => item.key));
  const canonicalKeys = coverage.map(item => item.canonicalWalkthroughKey);
  const assetByKey = new Map(list.map(item => [item.key, item]));
  const reused = list.filter(item => item.existingCatalogUrl);
  const recorded = list.filter(item => item.productionAction === "reuse-confirmed-generated-bundle");
  const pending = list.filter(item => !item.existingCatalogUrl && item.productionAction !== "reuse-confirmed-generated-bundle");
  const plan = {
    schemaVersion: 1, lessonId: "lesson-one-v2", generatedBy: "scripts/media-production/lesson-one-audio-plan.mjs",
    sources: { lesson: SOURCE, lessonSha256: sha(sourceText), uiModels: UI_SOURCE, uiModelsSha256: sha(JSON.stringify(models)), catalogs: catalogSources },
    status: "local-plan-no-provider-request-made",
    production: { provider: "elevenlabs", voices, recordedBundles: RECORDED_BUNDLES, remainingBundleInput: "plain-text-paragraphs-no-SSML", modelId: null, format: "mp3", synthesisPerformed: false, credentialsRead: false, networkRequests: 0, finalVoiceBindingRequired: true, cacheRule: "Person:text identifies playback. Production cache identity must additionally bind the chosen stock voiceId, model and settings; do not reuse unrelated old-course audio by text alone." },
    playbackPolicy: {
      beforeDecision: "All option previews, model examples and fixed-phrase readings use Nina as a quoted neutral reader. Never use an option's actor voice as a clue.",
      afterAcceptance: "Only the grammatical canonical model is spoken by the actual accepted actor. If the learner's meaning was accepted with form coaching, never synthesize their malformed input.",
      anonymousMessages: "Before the complete G5 solution is accepted/revealed, both A and B use the SAME Nina reader assets. Ana/Maya voices are forbidden until reveal; do not animate Nina as the identity asserted inside a quoted example.",
      optionalPreviews: "Manual playback of a visible grammatical candidate does not assert that candidate as true in the current scene. Wrong meaning is never automatically performed by a character.",
      narration: "English phrases only. Portuguese instructions, feedback, hints and names of controls are not synthesized.",
    },
    summary: {
      scenes: scenes.length, topLevelRounds: scenes.reduce((sum, scene) => sum + scene.rounds.length, 0), concreteUtteranceRounds: turns.length,
      correctActorUsesIncludingValidAlternatives: actorUses.length, previewAndModelUses: previewUses.length, allCoveredUses: uses.length,
      correctActorUniquePairs: actorKeys.size, neutralReaderUniquePairs: readerKeys.size, extraNeutralPairsBeyondActors: [...readerKeys].filter(key => !actorKeys.has(key)).length,
      totalUniquePairs: list.length, distinctEnglishTexts: new Set(list.map(asset => asset.text)).size,
      uniqueTextCharacters: list.reduce((sum, asset) => sum + asset.characters, 0),
      canonicalWalkthroughCharactersWithoutReuse: canonicalKeys.reduce((sum, key) => sum + assetByKey.get(key).characters, 0),
      allCorrectActorOccurrencesCharactersWithoutReuse: actorUses.reduce((sum, item) => sum + chars(item.text), 0),
      everyCoveredPreviewAndModelOnceCharactersWithoutReuse: previewUses.reduce((sum, item) => sum + chars(item.text), 0),
      allCoveredOccurrencesCharactersWithoutReuse: uses.reduce((sum, item) => sum + chars(item.text), 0),
      voiceBundles: bundles.length, bundleTextCharactersIncludingSeparators: bundles.reduce((sum, bundle) => sum + bundle.textCharacters, 0),
      existingCatalogPairs: reused.length, confirmedRecordedPairs: recorded.length, pendingUniquePairs: pending.length,
      pendingUniqueTextCharacters: pending.reduce((sum, asset) => sum + asset.characters, 0),
      remainingVoiceRequestsIfBundled: bundles.filter(bundle => bundle.pendingAssetKeys.length).length,
      remainingPlainTextCharactersIncludingSeparators: bundles.reduce((sum, bundle) => sum + bundle.pendingTextCharacters, 0),
      countingNote: "Counts are Unicode text characters including spaces/punctuation; bundle totals also include separators. They are not an asserted provider-credit price. Per-occurrence totals are hypothetical repeated generation, not a recommendation to make those requests.",
      perPerson: PEOPLE.map(person => ({ person, uniquePairs: list.filter(asset => asset.person === person).length, uniqueTextCharacters: list.filter(asset => asset.person === person).reduce((sum, asset) => sum + asset.characters, 0) })),
    },
    assets: list, uses, modelCards, bundles,
    jobs: bundles.map(bundle => ({ person: bundle.person, voiceSlot: bundle.voiceSlot, status: bundle.generationStatus, texts: bundle.texts, keys: bundle.assetKeys, text: bundle.plainText, inputFormat: bundle.person === "ana" ? "already-generated-SSML-do-not-repeat" : "plain-text", characters: bundle.textCharacters, pendingText: bundle.pendingPlainText, pendingCharacters: bundle.pendingTextCharacters, outputBundlePath: bundle.outputBundlePath })),
    coverage,
    expectedReusableReaderKeys: ["nina:We are a team.", "nina:They are a team."],
    excluded: ["I are… / You am… / We am… / They am… and arbitrary typed input", "Portuguese narration", "Old 36-scene greetings/questions/negation", "Actor voices as anonymous clues", "Extra name sentences never displayed or needed in this lesson"],
  };
  plan.audit = validateAudioPlan(plan, { scenes });
  return plan;
}

export function validateAudioPlan(plan, { scenes = LESSON_SCENES } = {}) {
  const checks = [];
  function check(id, condition, detail) { assert(condition, `${id}: ${detail}`); checks.push({ id, passed: true, detail }); }
  const assets = new Map(plan.assets.map(asset => [asset.key, asset]));
  check("deduplicated-person-text", assets.size === plan.assets.length, "One final asset per exact person:text pair");
  check("five-stock-voice-slots", plan.production.voices.length === 5 && new Set(plan.production.voices.map(voice => voice.person)).size === 5 && plan.production.voices.every(voice => voice.selection === "distinct-stock-elevenlabs-voice" && voice.cloning === false), "Five independent stock voice slots; no cloning");
  const boundIds = plan.production.voices.map(voice => voice.voiceId).filter(Boolean);
  check("distinct-configured-voices", new Set(boundIds).size === boundIds.length, "If voice IDs have been bound, they must be different");
  check("complete-grammatical-english-only", plan.assets.every(asset => /^(?:I am (?:Ana|Leo|Maya|Sam|Nina)|You are (?:Ana|Leo|Maya|Sam|Nina)|We are a team|They are a team)\.$/.test(asset.text)), "No malformed agreement, fragments or Portuguese speech assets");
  check("all-uses-resolve", plan.uses.every(use => assets.has(use.key) && use.key === keyFor(use.person, use.text)), "Every planned use resolves to its exact deduplicated asset");
  check("neutral-before-decision", plan.uses.filter(use => use.quoted).every(use => use.person === READER && use.actor === null), "Every preview/model uses the same Nina reader, not an asserted actor");
  check("anonymous-no-voice-leak", plan.uses.filter(use => use.anonymous && use.phase === "before-anonymous-solution").length === 2 && plan.uses.filter(use => use.anonymous && use.phase === "before-anonymous-solution").every(use => use.person === READER && use.quoted && use.key.startsWith("nina:")), "Both anonymous G5 messages use Nina before reveal");
  check("anonymous-actors-delayed", plan.uses.filter(use => use.anonymous && !use.quoted).every(use => use.phase === "after-anonymous-solution-revealed"), "Real G5 actor voices are delayed until the whole solution is revealed");
  for (const { scene, round } of concreteTurns(scenes)) for (const person of correctActors(round)) {
    check(`actor-coverage/${round.id}/${person}`, plan.uses.some(use => !use.quoted && use.sceneId === scene.id && use.roundId === round.id && use.key === keyFor(person, phraseText(round.expected))), "The canonical correct actor phrase is covered, including alternative correct speakers");
  }
  check("g4-two-valid-we-actors", plan.uses.some(use => use.roundId === "g4-inside" && !use.quoted && use.person === "ana") && plan.uses.some(use => use.roundId === "g4-inside" && !use.quoted && use.person === "leo"), "Both Ana and Leo can correctly say We in G4");
  check("models-complete-and-neutral", plan.modelCards.length === 12 && plan.modelCards.every(card => card.spokenEnglish.length && card.keys.every(key => assets.has(key) && key.startsWith("nina:"))), "All twelve model cards have complete neutral English readings");
  check("reuse-neutral-team-clips", plan.expectedReusableReaderKeys.every(key => assets.has(key)), "Nina We/They are each produced at most once and reused for anonymous messages, models and previews");
  const bundled = plan.bundles.flatMap(bundle => bundle.assetKeys);
  check("bundles-cover-assets-once", bundled.length === assets.size && new Set(bundled).size === assets.size && bundled.every(key => assets.has(key)), "Five bundles cover each final asset exactly once");
  check("reproducible-character-count", plan.summary.uniqueTextCharacters === plan.assets.reduce((sum, asset) => sum + chars(asset.text), 0), "Character totals derive from the exact English texts");
  return { passed: true, checks };
}

function selfTest(plan) {
  const copy = () => structuredClone(plan);
  const missing = copy(); missing.assets.pop();
  assert.throws(() => validateAudioPlan(missing), /all-uses-resolve/);
  const leaked = copy(); const before = leaked.uses.find(use => use.phase === "before-anonymous-solution");
  before.person = "ana"; before.key = keyFor("ana", before.text);
  assert.throws(() => validateAudioPlan(leaked), /neutral-before-decision|anonymous-no-voice-leak/);
  const incomplete = copy(); incomplete.uses = incomplete.uses.filter(use => !(use.roundId === "g4-inside" && use.person === "leo" && !use.quoted));
  assert.throws(() => validateAudioPlan(incomplete), /actor-coverage\/g4-inside\/leo/);
  const wrongGrammar = copy(); wrongGrammar.assets[0].text = "I are Ana.";
  assert.throws(() => validateAudioPlan(wrongGrammar), /complete-grammatical-english-only/);
  const duplicated = copy(); duplicated.assets.push(duplicated.assets[0]);
  assert.throws(() => validateAudioPlan(duplicated), /deduplicated-person-text/);
  const sameVoice = copy(); sameVoice.production.voices[0].voiceId = "same-stock-voice"; sameVoice.production.voices[1].voiceId = "same-stock-voice";
  assert.throws(() => validateAudioPlan(sameVoice), /distinct-configured-voices/);
  assert(plan.assets.some(asset => asset.key === "leo:We are a team."));
  assert(plan.assets.some(asset => asset.key === "nina:I am Ana."));
  assert(!plan.assets.some(asset => /(?:Hi|Hello|Are you|I'm|not)/.test(asset.text)));
  assert(!plan.assets.some(asset => asset.key === "nina:I am Leo."), "No unused name sentence should be generated");
  assert.equal(plan.summary.totalUniquePairs, 26, "Approved current lesson needs 19 actor pairs plus seven extra reader pairs");
  assert.equal(plan.summary.correctActorUniquePairs, 19);
  assert.equal(plan.summary.neutralReaderUniquePairs, 10);
  return { passed: true, negativeCases: 6, assertions: "coverage, all valid G4 speakers, anonymous voice isolation, grammatical English, deduplication, distinct stock voices, scope and minimality" };
}

async function readCatalogs(args) {
  const explicit = args.indexOf("--catalog");
  if (explicit >= 0) assert(args[explicit + 1] && !args[explicit + 1].startsWith("--"), "--catalog needs a local JSON path");
  const paths = explicit >= 0 ? [args[explicit + 1]] : ["src/features/first-encounters/lesson-one-audio.json", "src/features/first-encounters/audio.json", "output/lesson-one-audio/catalog.json"];
  const catalog = {}, sources = [];
  for (const candidate of paths) {
    const full = path.resolve(ROOT, candidate);
    try { await access(full); } catch { if (explicit >= 0) throw new Error(`Catalog not found: ${candidate}`); else continue; }
    const input = JSON.parse(await readFile(full, "utf8"));
    const entries = input.entries ?? input.catalog ?? input;
    assert(entries && typeof entries === "object" && !Array.isArray(entries), `Expected an object keyed by person:text: ${candidate}`);
    for (const [key, value] of Object.entries(entries)) if (PEOPLE.some(person => key.startsWith(`${person}:`)) && (typeof value === "string" || typeof value?.audioUrl === "string" || typeof value?.publicUrl === "string")) catalog[key] = value;
    sources.push(path.relative(ROOT, full));
  }
  return { catalog, catalogSources: sources };
}

async function main() {
  const args = process.argv.slice(2);
  const allowed = new Set(["--check", "--self-test", "--catalog"]);
  for (let i = 0; i < args.length; i++) { assert(allowed.has(args[i]), `Unknown option: ${args[i]}`); if (args[i] === "--catalog") i++; }
  const plan = buildAudioPlan(await readCatalogs(args));
  const tests = args.includes("--self-test") ? selfTest(plan) : null;
  const serialized = `${JSON.stringify(plan, null, 2)}\n`;
  if (args.includes("--check")) {
    const existing = await readFile(path.join(ROOT, OUTPUT), "utf8");
    assert.equal(existing, serialized, "Audio plan is stale. Re-run the local planner; this makes no provider calls.");
  } else if (!args.includes("--self-test")) {
    await mkdir(path.dirname(path.join(ROOT, OUTPUT)), { recursive: true });
    await writeFile(path.join(ROOT, OUTPUT), serialized);
  }
  process.stdout.write(`${JSON.stringify({ output: OUTPUT, status: "plan-only-no-provider-calls", summary: plan.summary, auditChecks: plan.audit.checks.length, ...(tests ? { selfTest: tests } : {}) }, null, 2)}\n`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
